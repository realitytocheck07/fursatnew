// Post-build step: node scripts/csp-report-only.mjs   (run after `npm run build`, on EVERY deploy)
// Appends two Content-Security-Policy-Report-Only lines per page to dist/_headers. NOTHING is enforced.
//   Policy A: everything except scripts (script-src is a placeholder that allows inline).
//   Policy B: script-src with the sha256 of every executable inline <script> of that page,
//             script-src-attr 'unsafe-hashes' with the hashes of the on*= handlers.
// Inline hashes change whenever the page's inline code changes, so this must be re-run after each build.
// JSON data blocks (application/ld+json, application/json) are not executed, CSP does not govern them: not hashed.
// Safe to run twice: the previous generated block is replaced.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';

const DIST = process.argv[2] || 'dist';
const HEADERS = join(DIST, '_headers');
const BEGIN = '# >>> csp-report-only (generated by scripts/csp-report-only.mjs, do not edit) >>>';
const END = '# <<< csp-report-only <<<';
const MAX = 2000;
if (!existsSync(HEADERS)) { console.error('missing ' + HEADERS + ' (run npm run build first)'); process.exit(1); }

const walk = (d) => readdirSync(d).flatMap((n) => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const sha = (s) => "'sha256-" + createHash('sha256').update(s, 'utf8').digest('base64') + "'";
const decode = (s) => s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
  .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const EXEC = (attrs) => { const m = /\stype\s*=\s*("([^"]*)"|'([^']*)'|(\S+))/i.exec(attrs); const t = m ? (m[2] ?? m[3] ?? m[4]).trim().toLowerCase() : ''; return t === '' || t === 'module' || t === 'text/javascript' || t === 'application/javascript'; };

const A_BASE = "default-src 'self'; font-src 'self' https://fonts.gstatic.com; "
  + "img-src 'self' data: blob: https://cdn.sanity.io https://*.cdninstagram.com https://*.fbcdn.net; "
  + "media-src 'self' blob:; connect-src 'self' https://api.web3forms.com https://fursat-feed.fursathyd.workers.dev; "
  + "style-src-attr 'unsafe-inline'; object-src 'none'; base-uri 'self'; form-action 'self' https://wa.me; "
  + "script-src 'self' 'unsafe-inline'";

const pages = walk(DIST).filter((f) => f.endsWith('.html')).map((f) => {
  const rel = relative(DIST, f).split(sep).join('/');
  if (rel === '404.html') return null; // served for any missing URL, no path to attach a header rule to
  const url = rel === 'index.html' ? '/' : '/' + rel.replace(/index\.html$/, '');
  return { f, url };
}).filter(Boolean).sort((a, b) => a.url.localeCompare(b.url));

const out = [BEGIN];
const rows = [];
for (const { f, url } of pages) {
  const html = readFileSync(f, 'utf8');
  const scripts = new Set(), styles = new Set(), handlers = new Set();
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (/\ssrc\s*=/i.test(m[1]) || !EXEC(m[1])) continue;
    scripts.add(sha(m[2]));
  }
  for (const m of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) styles.add(sha(m[1]));
  const stripped = html.replace(/<!--[\s\S]*?-->/g, '').replace(/(<(script|style)\b[^>]*>)[\s\S]*?(<\/\2>)/gi, '$1$3');
  for (const tag of stripped.matchAll(/<[a-zA-Z][^>"']*(?:"[^"]*"|'[^']*'|[^>"'])*>/g))
    for (const a of tag[0].matchAll(/\son[a-z]+\s*=\s*(?:"([^"]*)"|'([^']*)')/gi)) handlers.add(sha(decode(a[1] ?? a[2])));
  const A = A_BASE.replace("default-src 'self';", "default-src 'self'; style-src-elem 'self' https://fonts.googleapis.com " + [...styles].join(' ') + ';');
  const B = "script-src 'self' " + [...scripts].join(' ') + "; script-src-attr 'unsafe-hashes' " + [...handlers].join(' ');
  for (const [n, p] of [['A', A], ['B', B]]) {
    const line = '  Content-Security-Policy-Report-Only: ' + p;
    if (line.length >= MAX) { console.error(`FAIL ${url} policy ${n}: line is ${line.length} chars (limit ${MAX})`); process.exit(1); }
  }
  out.push(url, '  Content-Security-Policy-Report-Only: ' + A, '  Content-Security-Policy-Report-Only: ' + B);
  rows.push(`${url.padEnd(18)} A=${('  Content-Security-Policy-Report-Only: ' + A).length} B=${('  Content-Security-Policy-Report-Only: ' + B).length} inline-scripts=${scripts.size} style=${styles.size} on*=${handlers.size}`);
}
out.push(END);

let cur = readFileSync(HEADERS, 'utf8');
const i = cur.indexOf(BEGIN), j = cur.indexOf(END);
if (i !== -1 && j !== -1) cur = cur.slice(0, i).replace(/\n+$/, '\n') + cur.slice(j + END.length).replace(/^\n/, '');
writeFileSync(HEADERS, cur.replace(/\n*$/, '\n\n') + out.join('\n') + '\n');
console.log(rows.join('\n'));
console.log(`csp-report-only: ${pages.length} pages written to ${HEADERS} (report-only, not enforcing)`);
